const readline = require('readline');
const {ดึงข้อมูลคลิป} = require('./วิดีโอ');
const {เล่นเสียงคลิป} = require('./เสียง');

const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
});

// โลโก้คำว่า "เปา" ภาษาไทย ตัวใหญ่ ๆ เท่ ๆ หลากสี
function แสดงโลโก้เปา() {
    console.clear();
    // ใช้รหัสสี ANSI สลับสีให้คำว่า "เปา" เด่น ๆ
    console.log("\x1b[91m      ██████╗  █████╗  ██████╗ \x1b[0m");
    console.log("\x1b[93m      ██╔══██╗██╔══██╗██╔═══██╗\x1b[0m");
    console.log("\x1b[92m      ██████╔╝███████║██║   ██║\x1b[0m");
    console.log("\x1b[96m      ██╔═══╝ ██╔══██║██║   ██║\x1b[0m");
    console.log("\x1b[95m      ██║     ██║  ██║╚██████╔╝\x1b[0m");
    console.log("\x1b[94m      ╚═╝     ╚═╝  ╚═╝ ╚═════╝ \x1b[0m");
    console.log("\n\x1b[97m==============================================\x1b[0m");
    console.log("\x1b[92m           ยินดีต้อนรับสู่ ระบบ เปา.js           \x1b[0m");
    console.log("\x1b[97m==============================================\x1b[0m\n");
}

function หน้าหลัก() {
    แสดงโลโก้เปา();
    rl.question('\x1b[36m[เปา] วางลิงก์คลิปวิดีโอที่นี่: \x1b[0m', async (ลิงก์) => {
        if (!ลิงก์) {
            console.log('\x1b[31m[!] กรุณาใส่ลิงก์ให้ถูกต้อง\x1b[0m');
            setTimeout(หน้าหลัก, 2000);
            return;
        }

        console.log('\n\x1b[33m[*] กำลังดึงรายละเอียดจากคลิป สักครู่พี่...\x1b[0m');
        const ข้อมูล = await ดึงข้อมูลคลิป(ลิงก์);

        if (!ข้อมูล) {
            console.log('\x1b[31m[!] ไม่สามารถดึงข้อมูลคลิปนี้ได้\x1b[0m');
            setTimeout(หน้าหลัก, 3000);
            return;
        }

        // แสดงรายละเอียดภาษาไทยทั้งหมด
        console.log(`\n\x1b[92m=== รายละเอียดคลิป ===\x1b[0m`);
        console.log(`📌 ชื่อคลิป: ${ข้อมูล.หัวข้อ}`);
        console.log(`👤 ช่อง: ${ข้อมูล.ช่อง}`);
        console.log(`⏱️ ความยาว: ${ข้อมูล.ความยาว} วินาที`);
        console.log(`👁️ ยอดวิว: ${ข้อมูล.ยอดวิว} ครั้ง`);
        console.log(`======================\n`);

        ถามเรื่องเปิดเสียง(ข้อมูล.ลิงก์เสียง);
    });
}

function ถามเรื่องเปิดเสียง(ลิงก์เสียง) {
    rl.question('\x1b[35m[?] คุณต้องการจะเปิดเสียงนี้ไหม? (y/n): \x1b[0m', (คำตอบ) => {
        const choice = คำตอบ.toLowerCase().trim();
        if (choice === 'y') {
            console.log('\x1b[32m[+] กำลังเปิดเสียงในเครื่องให้ทันที...\x1b[0m');
            เล่นเสียงคลิป(ลิงก์เสียง, () => {
                console.log('\n\x1b[32m[✓] เล่นเสียงเสร็จสิ้น!\x1b[0m');
                เมนูจบ();
            });
        } else if (choice === 'n') {
            console.log('\x1b[31m[-] ยกเลิกการเปิดเสียง\x1b[0m');
            เมนูจบ();
        } else {
            console.log('\x1b[33m[!] ตอบแค่ y หรือ n เท่านั้นนะพี่\x1b[0m');
            ถามเรื่องเปิดเสียง(ลิงก์เสียง);
        }
    });
}

function เมนูจบ() {
    rl.question('\nกด Enter เพื่อกลับหน้าหลัก...', () => {
        หน้าหลัก();
    });
}

หน้าหลัก();
